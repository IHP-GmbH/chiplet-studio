"""Write the Python API reference page from the built chiplet_studio module.

The page is generated, never edited by hand: the module the build makes is the
one source of what the API offers, and its pybind11 signatures are what a
script sees. Run it after a build, inside the image the build used:

    python3 scripts/gen-api-reference.py build/python > docs/reference/python-api.md

The output depends only on the module, in its definition order where pybind11
keeps one and sorted otherwise, so a second run over the same build writes the
same bytes. It exits 2 when the module cannot be imported from the directory
given, rather than writing a page about whatever else is on sys.path.
"""
import importlib.util
import inspect
import pathlib
import sys

MODULE = "chiplet_studio"


def load(module_dir):
    found = sorted(pathlib.Path(module_dir).glob(MODULE + "*.so"))
    if len(found) != 1:
        print("ABORT: expected one %s*.so in %s, found %d"
              % (MODULE, module_dir, len(found)), file=sys.stderr)
        sys.exit(2)
    spec = importlib.util.spec_from_file_location(MODULE, found[0])
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def doc_lines(obj):
    return [l.rstrip() for l in (inspect.getdoc(obj) or "").splitlines()]


def is_enum(cls):
    return hasattr(cls, "__members__") and hasattr(cls, "value")


def public(names):
    return [n for n in names if not n.startswith("_") or n == "__init__"]


def write_callable(out, name, obj):
    # pybind11 puts the signatures first, one per overload, then the docstring.
    lines = doc_lines(obj) or [name + "(...)"]
    sigs = [l for l in lines if l.startswith(name + "(")
            or (l[:1].isdigit() and ". " + name + "(" in l)]
    rest = [l for l in lines if l not in sigs and l != "Overloaded function."]
    out.append("```")
    out.extend(s.split(". ", 1)[1] if s[:1].isdigit() else s for s in sigs or [name])
    out.append("```")
    text = "\n".join(rest).strip()
    if text:
        out.extend(["", text])
    out.append("")


def write_class(out, name, cls):
    out.extend(["## `%s`" % name, ""])
    text = "\n".join(doc_lines(cls)).strip()
    if text:
        out.extend([text, ""])
    if is_enum(cls):
        out.append("Values: " + ", ".join("`%s`" % m for m in cls.__members__) + ".")
        out.append("")
        return
    members = vars(cls)
    props = [n for n in public(members) if isinstance(members[n], property)]
    calls = [n for n in public(members) if n not in props and callable(members[n])]
    if props:
        out.append("Attributes: " + ", ".join("`%s`" % p for p in props) + ".")
        out.append("")
    for n in calls:
        out.extend(["### `%s.%s`" % (name, n), ""])
        write_callable(out, n, getattr(cls, n))


def main(argv):
    if len(argv) != 2:
        sys.exit("usage: gen-api-reference.py <directory holding %s*.so>" % MODULE)
    mod = load(argv[1])
    names = public(vars(mod))
    classes = [n for n in names if inspect.isclass(getattr(mod, n))]
    funcs = [n for n in names if n not in classes and callable(getattr(mod, n))]
    out = ["# Python API reference", "",
           "Generated by `scripts/gen-api-reference.py` from the built `%s` "
           "module. Do not edit by hand." % MODULE, ""]
    text = "\n".join(doc_lines(mod)).strip()
    if text:
        out.extend([text, ""])
    for n in classes:
        write_class(out, n, getattr(mod, n))
    if funcs:
        out.extend(["## Functions", ""])
        for n in funcs:
            out.extend(["### `%s`" % n, ""])
            write_callable(out, n, getattr(mod, n))
    sys.stdout.write("\n".join(out).rstrip() + "\n")


if __name__ == "__main__":
    main(sys.argv)
